import os

base_path = "/content/RDD2022/RDD_SPLIT"

for split in ["train", "val", "test"]:
    label_folder = os.path.join(base_path, split, "labels")

    converted = 0

    for file in os.listdir(label_folder):
        if not file.endswith(".txt"):
            continue

        file_path = os.path.join(label_folder, file)

        with open(file_path, "r") as f:
            content = f.read().strip()

        # Empty label file
        if not content:
            continue

        values = content.split()

        # Every object contains 5 values:
        # class_id, x_center, y_center, width, height
        if len(values) % 5 != 0:
            print("Problem in:", file)
            print("Number of values:", len(values))
            continue

        new_lines = []

        for i in range(0, len(values), 5):
            new_lines.append(" ".join(values[i:i+5]))

        with open(file_path, "w") as f:
            f.write("\n".join(new_lines))

        converted += 1

    print(f"{split}: {converted} label files converted")

print("\nLabel conversion completed!")

